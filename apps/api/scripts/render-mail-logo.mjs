// Renders the existing AYVO wordmark (apps/web/public/brand/ayvo-wordmark.svg) to the PNG that
// authentication e-mails embed (CID). E-mail clients do not show SVG; the PNG is the same vector
// drawn once at a fixed width with its own aspect ratio — never redrawn or stretched. Output:
// src/common/ayvo-logo-png.ts (base64, compiled into dist: no file is read at runtime).
//   node scripts/render-mail-logo.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { createCanvas, loadImage } from '@napi-rs/canvas';

const apiRoot = resolve(import.meta.dirname, '..');
const svgPath = resolve(apiRoot, '../web/public/brand/ayvo-wordmark.svg');
const WIDTH = 240; // shown at 120 px: sharp on 2x screens

const svg = await readFile(svgPath);
const image = await loadImage(svg);
const height = Math.round((WIDTH * image.height) / image.width);
const canvas = createCanvas(WIDTH, height);
canvas.getContext('2d').drawImage(image, 0, 0, WIDTH, height);
const png = canvas.toBuffer('image/png');
await writeFile(
  resolve(apiRoot, 'src/common/ayvo-logo-png.ts'),
  [
    '// Generated by scripts/render-mail-logo.mjs from apps/web/public/brand/ayvo-wordmark.svg.',
    '// Do not edit by hand; re-run the script if the wordmark changes.',
    `export const AYVO_LOGO_PNG_WIDTH = ${WIDTH};`,
    `export const AYVO_LOGO_PNG_HEIGHT = ${height};`,
    `export const AYVO_LOGO_PNG_BASE64 =\n  '${png.toString('base64')}';`,
    '',
  ].join('\n'),
);
console.log(`ayvo-logo-png.ts: ${WIDTH}x${height}, ${png.length} bytes`);
