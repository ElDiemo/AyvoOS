import { z } from 'zod';
import { labelTemplateVersionRefSchema } from './labels.js';

/** Bottles, lifecycle events and creation batches (assets module). */

export const BOTTLE_CREATION_MIN = 1;
export const BOTTLE_CREATION_MAX = 1000;

export const bottleCodeSchema = z
  .string()
  .regex(/^AYV-B-\d{6,}$/, 'Expected a code like AYV-B-000001');
export const bottleCreationBatchCodeSchema = z
  .string()
  .regex(/^BC-\d{6,}$/, 'Expected a code like BC-000001');

/** Opaque public QR token: 128 random bits, base64url without padding (22 characters). */
export const publicTokenSchema = z.string().regex(/^[A-Za-z0-9_-]{22}$/);

export const bottleStatusSchema = z.enum(['CREATED']);
export type BottleStatus = z.infer<typeof bottleStatusSchema>;

export const bottleEventTypeSchema = z.enum(['CREATED']);
export type BottleEventType = z.infer<typeof bottleEventTypeSchema>;

/** POST /api/admin/bottle-registrations */
export const createBottleRegistrationRequestSchema = z.object({
  /**
   * Idempotency key, generated by the client once per intended registration (e.g. per
   * confirmation). Retrying with the same key returns the original batch; never a second one.
   */
  requestId: z.uuid(),
  labelTemplateVersionId: z.uuid(),
  quantity: z.number().int().min(BOTTLE_CREATION_MIN).max(BOTTLE_CREATION_MAX),
});
export type CreateBottleRegistrationRequest = z.infer<typeof createBottleRegistrationRequestSchema>;

export const bottleCreationBatchSchema = z.object({
  code: z.string(),
  quantityRequested: z.number().int(),
  quantityCreated: z.number().int(),
  firstBottleCode: z.string(),
  lastBottleCode: z.string(),
  labelTemplate: labelTemplateVersionRefSchema,
  createdAt: z.iso.datetime(),
});
export type BottleCreationBatch = z.infer<typeof bottleCreationBatchSchema>;

export const bottleSummarySchema = z.object({
  code: z.string(),
  status: bottleStatusSchema,
  creationBatchCode: z.string(),
  labelTemplate: labelTemplateVersionRefSchema,
  createdAt: z.iso.datetime(),
});
export type BottleSummary = z.infer<typeof bottleSummarySchema>;

export const bottleEventSchema = z.object({
  type: bottleEventTypeSchema,
  occurredAt: z.iso.datetime(),
  recordedAt: z.iso.datetime(),
});
export type BottleEvent = z.infer<typeof bottleEventSchema>;

export const bottleDetailSchema = bottleSummarySchema.extend({
  /** The stable public URL encoded in the bottle's QR code. */
  publicUrl: z.url(),
  /** Oldest first. */
  events: z.array(bottleEventSchema),
});
export type BottleDetail = z.infer<typeof bottleDetailSchema>;

export const PAGE_SIZE_MAX = 100;

export const bottleListQuerySchema = z.object({
  page: z.coerce.number().int().min(1).default(1),
  pageSize: z.coerce.number().int().min(1).max(PAGE_SIZE_MAX).default(50),
  /** Exact bottle code or number: "AYV-B-000123", "000123" or "123". */
  search: z.string().trim().max(32).optional(),
  /** Creation batch code, e.g. "BC-000001". */
  batch: z.string().trim().max(32).optional(),
  /** Label template id (any version). */
  templateId: z.uuid().optional(),
});
export type BottleListQuery = z.infer<typeof bottleListQuerySchema>;

export function pageSchema<T extends z.ZodType>(item: T) {
  return z.object({
    items: z.array(item),
    page: z.number().int(),
    pageSize: z.number().int(),
    total: z.number().int(),
  });
}

export const bottleListResponseSchema = pageSchema(bottleSummarySchema);
export type BottleListResponse = z.infer<typeof bottleListResponseSchema>;

export const bottleCreationBatchListResponseSchema = pageSchema(bottleCreationBatchSchema);
export type BottleCreationBatchListResponse = z.infer<typeof bottleCreationBatchListResponseSchema>;

/**
 * Public bottle passport (GET /api/public/bottles/:token). An explicit whitelist: no internal
 * IDs, no operator, warehouse or hotel data, no CO2e (doc 011).
 */
export const publicBottlePassportSchema = z
  .object({
    bottleCode: z.string(),
    /** Completed reuse cycles as defined in ADR 0011. */
    reuseCycles: z.number().int().nonnegative(),
  })
  .strict();
export type PublicBottlePassport = z.infer<typeof publicBottlePassportSchema>;
